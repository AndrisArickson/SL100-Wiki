#!/usr/bin/env python3
"""Line up each SL100 species (02) with its d20 entries and its Legends article, and list d20 species SL100 has not used.
Lookup only.   -> Source_Text/collation/species_xref.md  (quotes d20 ability modifiers, so it stays out of git)"""
import csv, re, sys
from pathlib import Path
WIKI = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(WIKI / "tools"))
import common as C   # noqa: E402
TEXT = WIKI.parent / "Source_Text"


def key(s):
    s = re.sub(r"\(.*?\)|/legends", "", s.lower())
    s = re.sub(r"[^a-z]", "", s)
    return s[:-1] if s.endswith("s") and len(s) > 4 else s


def main():
    sl = list(csv.DictReader(open(WIKI / "docs/collation/species.csv", encoding="utf-8")))
    d20 = [r for r in csv.DictReader(open(TEXT / "tables/d20_species.csv", encoding="utf-8")) if r["kind"] == "species"]
    con = C.db_connect()
    titles = {key(t): t for (t,) in con.execute("SELECT title FROM pages WHERE ns=0 AND path IS NOT NULL AND title LIKE '%/Legends'")}
    by = {}
    for r in d20:
        by.setdefault(key(r["species"]), []).append(r)
    md = ["# SL100 species vs d20 species vs Legends articles", "", "Generated by `tools/collate/species_xref.py`. Names matched loosely "
          "(case, punctuation, plural, bracketed parts ignored). d20 values are quoted as printed (OCR slips possible).", "",
          "## The %d SL100 species (02)" % len(sl), ""]
    used = set()
    for s in sl:
        k = key(s["species"]); used.add(k)
        md.append("### %s" % s["species"])
        md.append("- SL100 (02): characteristics %s; talents %s; Mv %s Fate %s Res %s" % (s["characteristics"] or "(none written)", s["talents"] or "(none)",
                  s["movement"] or "-", s["fate"] or "-", s["resilience"] or "-"))
        md.append("- Legends article: %s" % (("[[%s]]" % titles[k]) if k in titles else "(no /Legends title of that name)"))
        for r in by.get(k, []):
            md.append("- d20 %s p.%s: abilities %s; size %s; speed %s; skills %s; other: %s" % (r["book"][3:], r["page"], r["ability_modifiers"] or "-",
                      r["size"] or "-", r["speed"] or "-", r["skill_bonuses"][:120] or "-", r["other_traits"][:160] or "-"))
        if k not in by:
            md.append("- d20: no species entry of that name found")
        md.append("")
    rest = sorted({r["species"] for r in d20 if key(r["species"]) not in used and len(r["species"]) > 2})
    md += ["## d20 species not (yet) in SL100 (%d)" % len(rest), "", ", ".join(rest)]
    out = TEXT / "collation" / "species_xref.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(md) + "\n", encoding="utf-8")
    print("SL100 species %d, with d20 match %d; d20 species not in SL100 %d" % (len(sl), sum(1 for s in sl if key(s["species"]) in by), len(rest)))


if __name__ == "__main__":
    main()

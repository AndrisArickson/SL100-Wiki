#!/usr/bin/env python3
"""Find leftover or inconsistent vocabulary in the SL100 design documents (WFRP/d20 terms, placeholders, dead page refs).
Finding only - nothing is changed.   ->  docs/collation/vocab_hits.csv, vocab_report.md
Edit TERMS below to add or drop searches. 'group' says why a term is listed (taken from the rules design summary)."""
import csv, re
from collections import defaultdict
from pathlib import Path
import sys

WIKI = Path(__file__).resolve().parent.parent.parent
OUT = WIKI / "docs" / "collation"
sys.path.insert(0, str(WIKI / "tools"))
import common as C   # noqa: E402
DOCS = sorted(p for p in WIKI.glob("*.md") if p.name not in ("README.md", "NOTICE.md") + C.SUPERSEDED)
TERMS = [  # (group, label, regex)
    ("placeholder", "xx placeholder", r"\bxx+\b"),
    ("placeholder", "TBD / TODO", r"\b(TBD|TODO|tbc)\b"),
    ("dead reference", "page number", r"\bpages? \d+\b"),
    ("dead reference", "table xx / see table", r"\btable (xx|\d+[-.]\d+)\b"),
    ("old name", "Warhammer", r"\bWarhammer\b|\bWFRP\b|\bWFRPG\b"),
    ("old name", "New Star Wars / Star Wars WFRPG", r"New Star Wars|Star Wars WFRPG"),
    ("d20 term", "Reflex/Fortitude/Will save or DC", r"\b(Reflex|Fortitude|Will) (save|saving throw|DC)\b|\bDC ?\d+\b"),
    ("d20 term", "squares", r"\bsquares?\b"),
    ("d20 term", "standard / full-round / swift action", r"\b(standard|full[- ]round|swift|move|half)[- ]actions?\b"),
    ("d20 term", "ranks", r"\branks?\b"),
    ("d20 term", "d20 / Saga", r"\bd20\b|\bSaga Edition\b|\bSWSE\b"),
    ("characteristic", "Dexterity / Dex", r"\bDex(terity)?\b"),
    ("characteristic", "Intuition (for Initiative?)", r"\bIntuition\b"),
    ("characteristic", "Agi (vs Ag)", r"\bAgi\b"),
    ("skill rename", "Read/Write (now Datapad Literate)", r"\bRead/Write\b"),
    ("skill rename", "Heal (now Medicine)", r"\bHeal\b(?! ?ing)"),
    ("skill rename", "Trade (now Profession)", r"\bTrade \("),
    ("skill rename", "Consume Alcohol (now Consume Intoxicant)", r"\bConsume Alcohol\b"),
    ("skill rename", "Secret Signs (now Codes)", r"\bSecret Signs\b"),
    ("skill rename", "Pick Lock / Set Trap", r"\b(Pick Lock|Set Trap)\b"),
    ("skill rename", "Pray / Channelling / Magick", r"\b(Pray|Channell?ing|Magick)\b"),
    ("skill rename", "Drive / Row / Sail / Ride", r"\b(Drive|Row|Sail|Ride)\s*\("),
    ("fantasy residue", "Old World / Empire city names", r"\b(Old World|Altdorf|Reikland|Sigmar|Ulric|Nuln|Middenheim|Karl Franz)\b"),
    ("fantasy residue", "coins", r"\b(gold crowns?|GC|shillings?|s/|pennies|brass pennies|d10 GC|\d+d10 GC)\b"),
    ("fantasy residue", "medieval kit", r"\b(halberd|riverboat|longbow|crossbow|horse|cart|wagon|quill|parchment|tavern)\b"),
    ("fantasy residue", "magic words", r"\b(spells?|wizard|witch|miscast|Winds of Magic|Lore of)\b"),
    ("units", "yards", r"\byards?\b"),
    ("units", "feet / ft", r"\b\d+ ?(ft|feet)\b"),
]


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    hits, cnt = [], defaultdict(lambda: defaultdict(int))
    for p in DOCS:
        for i, ln in enumerate(p.read_text(encoding="utf-8", errors="replace").split("\n"), 1):
            for g, label, rx in TERMS:
                for m in re.finditer(rx, ln, re.I if g not in ("characteristic",) else 0):
                    a = max(0, m.start() - 50)
                    hits.append({"doc": p.name, "line": i, "group": g, "term": label, "matched": m.group(0),
                                 "context": re.sub(r"\s+", " ", ln[a:m.end() + 50]).strip()})
                    cnt[label][C.page_of(p.name)] += 1
    with open(OUT / "vocab_hits.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=["doc", "line", "group", "term", "matched", "context"])
        w.writeheader(); w.writerows(hits)
    order = list(C.RULES_PAGES.values())
    docs = sorted({k for c in cnt.values() for k in c}, key=lambda d: (order.index(d) if d in order else len(order), d))
    md = ["# Vocabulary scan of the SL100 documents", "", "Generated by `tools/collate/vocab.py`. Counts of each search term per document; "
          "every hit with its line and context is in `vocab_hits.csv`. Some hits are legitimate uses (e.g. 'ranks' in a "
          "military sense, 'Heal' as a verb) - this is a list to look through, not a list of errors.", "",
          "| Term | " + " | ".join(docs) + " | total |", "|---" * (len(docs) + 2) + "|"]
    for g, label, _ in TERMS:
        c = cnt.get(label)
        if c:
            md.append("| %s | %s | %d |" % (label, " | ".join(str(c.get(d, "")) for d in docs), sum(c.values())))
    (OUT / "vocab_report.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))
    print("hits:", len(hits))


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Put every statement of a starship's or vehicle's numbers side by side, from all sources, without choosing between them.

Sources: 'Star Wars Space Ships.md', 'Starships circa 3000-4000 BBY.md', 'Star Wars Mounts_Vehicles.md' (tables),
the d20 books (Source_Text/tables/starship.csv, vehicle.csv) and the Legends wiki infobox.
Rows are grouped by the Legends article they match (same matcher as tools/books/wikimatch.py).

  ships_compare.py -> Source_Text/collation/ships_compare.csv (long format: one row per source statement)
                      Source_Text/collation/ships_compare.md  (ships stated in 2+ sources, values side by side)
The d20 values are book data; this output keeps only cost/size/crew/speed/hyperdrive-type figures and page refs.
"""
import csv, re, sys
from collections import defaultdict
from pathlib import Path

WIKI = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(WIKI / "tools" / "books"))
import wikimatch as WM   # noqa: E402

OUT = WM.TEXT / "collation"     # contains d20 book figures, so it stays outside git with the other book data
DOCS = ["Star Wars Space Ships.md", "Starships circa 3000-4000 BBY.md", "Star Wars Mounts_Vehicles.md"]
KEEP = re.compile(r"cost|price|size|length|crew|passeng|hyperdrive|speed|mglt|kph|velocity|maneuver|hull|shield|availab|era|faction|class|astromech|armament|weapons?", re.I)


def plain(s):
    s = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", s)
    s = re.sub(r"<br\s*/?>", " ", s)
    s = re.sub(r"&#\d+;|[*_`]", " ", s)
    return re.sub(r"\s+", " ", s).strip()


def doc_rows():
    for name in DOCS:
        p = WIKI / name
        if not p.exists():
            continue
        head, sec = None, ""
        for i, ln in enumerate(p.read_text(encoding="utf-8", errors="replace").split("\n"), 1):
            if ln.startswith("#"):
                sec = plain(ln.lstrip("#")); head = None; continue
            if not ln.startswith("|"):
                head = None if not ln.strip() else head
                continue
            cells = [plain(c) for c in ln.strip().strip("|").split("|")]
            if all(re.fullmatch(r"[-: ]*", c) for c in cells):
                continue
            if head is None:
                head = cells; continue
            if len(cells) < 2 or not cells[0] or cells[0] in ("M",):
                continue
            vals = {h: v for h, v in zip(head, cells[1:] if head[0] == "" else cells) if v}
            nm = cells[0]
            yield {"source": name, "line": i, "section": sec, "name": nm,
                   "values": "; ".join("%s=%s" % (k, v) for k, v in vals.items() if k != head[0] and KEEP.search(k))}


def d20_rows():
    for fn in ("starship.csv", "vehicle.csv", "core_vehicle.csv"):
        f = WM.TAB / fn
        if not f.exists():
            continue
        for r in csv.DictReader(open(f, encoding="utf-8")):
            vals = {k: v for k, v in r.items() if v and KEEP.search(k) and k not in ("check",)}
            yield {"source": "d20 " + r.get("book", ""), "line": r.get("page", ""), "section": fn, "name": r.get("name", ""),
                   "values": "; ".join("%s=%s" % (k, v) for k, v in vals.items())}


def main():
    w = WM.Wiki()
    groups = defaultdict(list)
    rows = []
    for r in list(doc_rows()) + list(d20_rows()):
        kind = "vehicle" if "Vehicle" in r["source"] or r["section"] in ("vehicle.csv", "core_vehicle.csv") else "starship"
        how, title, cands = WM.match(w, r["name"], kind)
        r.update(match=how, wiki_title=title, candidates=" | ".join(cands))
        rows.append(r)
        if title:
            groups[title].append(r)
    for title, rs in groups.items():   # one wiki row per matched article
        tpl, facts = w.info(title)
        rows.append({"source": "Legends wiki", "line": "", "section": tpl, "name": title, "match": "", "wiki_title": title, "candidates": "",
                     "values": "; ".join("%s=%s" % (k, v) for k, v in facts.items() if KEEP.search(k))})
        groups[title].append(rows[-1])
    OUT.mkdir(parents=True, exist_ok=True)
    cols = ["wiki_title", "source", "line", "section", "name", "match", "values", "candidates"]
    with open(OUT / "ships_compare.csv", "w", newline="", encoding="utf-8") as fh:
        wr = csv.DictWriter(fh, fieldnames=cols, extrasaction="ignore")
        wr.writeheader(); wr.writerows(sorted(rows, key=lambda r: (r["wiki_title"] or "~" + r["name"], r["source"])))
    multi = {t: rs for t, rs in groups.items() if len({r["source"] for r in rs if r["source"] != "Legends wiki"}) >= 2}
    md = ["# Ships and vehicles stated in more than one source", "",
          "Generated by `tools/collate/ships_compare.py`. Values are copied as written in each source; no source is preferred. "
          "%d articles are stated in two or more SL100/d20 sources; the full long list (%d rows, including unmatched names) is "
          "`ships_compare.csv`." % (len(multi), len(rows)), ""]
    for t in sorted(multi):
        md.append("## %s" % t.replace("/Legends", ""))
        md.append("")
        for r in multi[t]:
            md.append("- **%s**%s: %s" % (r["source"], (" (line/page %s)" % r["line"]) if r["line"] else "", r["values"] or "(no figures)"))
        md.append("")
    unmatched = [r for r in rows if not r["wiki_title"] and r["source"] in DOCS]
    md += ["## Names in the SL100 ship and vehicle documents with no matching Legends article (%d)" % len(unmatched), ""]
    md += ["- %s (%s line %s)%s" % (r["name"], r["source"], r["line"], ("; candidates: " + r["candidates"]) if r["candidates"] else "") for r in unmatched]
    (OUT / "ships_compare.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("rows %d, matched articles %d, in 2+ sources %d, unmatched doc names %d" % (len(rows), len(groups), len(multi), len(unmatched)))


if __name__ == "__main__":
    main()

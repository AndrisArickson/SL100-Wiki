#!/usr/bin/env python3
"""Publish the collation reports as SL100: wiki pages (generated - edit the reports' scripts, not these pages).

  wiki_pages.py   writes SL100:Character creation, SL100:Collation (+ subpages), SL100:Careers compared with WFRP,
                  SL100:Source books.  Rules pages (Species, Careers, Talents...) are NOT touched.
"""
import csv, json, re, sys
from pathlib import Path

WIKI = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(WIKI / "tools"))
import common as C   # noqa: E402

COL = WIKI / "docs" / "collation"
TEXT = WIKI.parent / "Source_Text"
STAMP = "<!-- Generated by tools/collate/wiki_pages.py from %s. Changes made here are replaced when it is re-run. -->\n"


def md_inline(s):
    s = re.sub(r"\[([^\]]+)\]\(https?://starwars\.(?:fandom|wikia)\.com/wiki/([^)\s]+)\)",
               lambda m: "[[%s|%s]]" % (m.group(2).replace("_", " "), m.group(1)), s)
    s = re.sub(r"\[([^\]]+)\]\((https?://[^)\s]+)\)", r"[\2 \1]", s)
    s = re.sub(r"\*\*(.+?)\*\*", r"'''\1'''", s)
    s = re.sub(r"(?<![*\w])\*(?!\s)(.+?)(?<!\s)\*(?![*\w])", r"''\1''", s)
    s = re.sub(r"`([^`]+)`", r"<code>\1</code>", s)
    return s


def md_to_wiki(md):
    out, rows = [], []

    def flush():
        if rows:
            out.append('{| class="wikitable sortable"')
            for i, r in enumerate(rows):
                if i == 1 and all(re.fullmatch(r":?-{2,}:?", c.strip()) or not c.strip() for c in r):
                    continue
                out.append("|-")
                out.append(("! " if i == 0 else "| ") + (" !! " if i == 0 else " || ").join(md_inline(c.strip()) or " " for c in r))
            out.append("|}")
            rows.clear()
    for ln in md.split("\n"):
        if ln.startswith("|"):
            rows.append(ln.strip().strip("|").split("|")); continue
        flush()
        h = re.match(r"^(#{1,6})\s+(.*)$", ln)
        if h:
            n = max(2, len(h.group(1)))
            out.append("%s %s %s" % ("=" * n, md_inline(h.group(2)), "=" * n)); continue
        li = re.match(r"^(\s*)[-*]\s+(.*)$", ln)
        if li:
            out.append("*" * (1 + len(li.group(1)) // 2) + " " + md_inline(li.group(2))); continue
        out.append(md_inline(ln))
    flush()
    return "\n".join(out)


def write_page(con, title, text):
    taken = {r[0].lower() for r in con.execute("SELECT path FROM pages WHERE path IS NOT NULL AND title<>?", (title,))}
    r = con.execute("SELECT path FROM pages WHERE title=?", (title,)).fetchone()
    rel = r[0] if r and r[0] else C.page_relpath(title, 3000, taken)
    C.write_atomic(C.PAGES_DIR / rel, text)
    if r:
        con.execute("UPDATE pages SET path=?, ts=?, bytes=?, status='local', local_edit=1 WHERE title=?", (rel, C.now_iso(), len(text.encode()), title))
    else:
        con.execute("INSERT INTO pages(title,ns,status,path,ts,bytes,local_edit,priority) VALUES(?,?,?,?,?,?,1,0)",
                    (title, 3000, "local", rel, C.now_iso(), len(text.encode())))
    C.record_page_meta(con, title, text)
    print("wrote", title, "->", rel)


def main():
    con = C.db_connect()
    # Character creation
    ca = (COL / "character_assembly.md").read_text(encoding="utf-8")
    body = md_to_wiki(re.sub(r"^# .*\n", "", ca, count=1))
    write_page(con, "SL100:Character creation", STAMP % "docs/collation/character_assembly.md" +
               "This page collates how a character is built from the rules documents, step by step, '''as they are written today'''. "
               "It adds no rules of its own; where the documents are silent it says so. The rules themselves are on "
               "[[SL100:Characteristics]], [[SL100:Species]], [[SL100:Origin]], [[SL100:Careers]] and the Faction page.\n\n" + body +
               "\n\n[[Category:SL100]] [[Category:SL100 collation]]")
    # Collation index + subpages
    subs = [("Legends check", "legends_check_summary.md", "Names in the rules documents looked up in the Legends wiki: canon-only names, canon links."),
            ("Talent and skill lists", "lists_report.md", "07 vs Talent List vs 06 vs 05: missing, undefined, duplicate talents and skills."),
            ("Vocabulary", "vocab_report.md", "Leftover WFRP / d20 / fantasy words, placeholders and dead page references."),
            ("Intuition fixes", "intuition_fixes.md", "Where 'Intuition' was changed to 'Initiative' (characteristic uses only).")]
    cards = []
    for name, fn, blurb in subs:
        f = COL / fn
        if f.exists():
            write_page(con, "SL100:Collation/" + name, STAMP % ("docs/collation/" + fn) + md_to_wiki(re.sub(r"^# .*\n", "", f.read_text(encoding="utf-8"), count=1))
                       + "\n\n[[Category:SL100 collation]]")
            cards.append("{{SL100 Card|link=SL100:Collation/%s|title=%s|text=%s}}" % (name, name, blurb))
    cards.append("{{SL100 Card|link=SL100:Careers compared with WFRP|title=Careers compared with WFRP|text=Which WFRP 4e careers SL100 has, which are missing, and what changed level by level.}}")
    cards.append("{{SL100 Card|link=SL100:Character creation|title=Character creation|text=What each layer gives: characteristics, species, origin, career, faction.}}")
    write_page(con, "SL100:Collation", STAMP % "the collation scripts" +
               "Reports that line up the rules documents, the WFRP rulebook, the d20 books and the Legends wiki side by side. "
               "They are lookups and comparisons only - no rules are decided here. Re-run them with <code>./wiki.sh collate</code>.\n\n"
               "'''[/match-review Review d20 item matches]''' - confirm or correct which Legends article each d20 weapon, armour, droid, vehicle "
               "and starship belongs to, one click per item (local only).\n\n"
               '<div class="sl-cards small">\n' + "\n".join(cards) + "\n</div>\n\n"
               "Files behind these pages: <code>SL100-Wiki/docs/collation/</code> (in git) and <code>Source_Text/tables</code>, "
               "<code>Source_Text/collation</code> (d20 and WFRP data, kept off GitHub).\n\n[[Category:SL100]] [[Category:SL100 collation]]")
    # Careers compared (summary only - no WFRP text)
    cc = TEXT / "collation" / "careers_compare.md"
    if cc.exists():
        t = cc.read_text(encoding="utf-8")
        keep = []
        for sec in re.split(r"(?=^## )", t, flags=re.M):
            if sec.startswith(("## WFRP careers by class", "## WFRP careers with no", "## SL100 careers with no", "## WFRP careers where")):
                keep.append(re.sub(r": levels .*$", "", sec, flags=re.M))
        head = t.split("## ")[0]
        write_page(con, "SL100:Careers compared with WFRP", STAMP % "Source_Text/collation/careers_compare.md (summary only)" +
                   md_to_wiki(re.sub(r"^# .*\n", "", head, count=1) + "\n".join(keep)) +
                   "\n\nThe level-by-level differences (skills, talents and trappings of every matching career) are in "
                   "<code>Source_Text/collation/careers_compare.md</code> on your computer; they quote the WFRP rulebook, so they stay off the wiki.\n\n"
                   "[[Category:SL100 collation]]")
    # Source books
    rows = []
    for d in sorted(TEXT.glob("SW_*")):
        if (d / "pages").is_dir():
            rows.append("|-\n| %s || %d" % (d.name[3:].replace("_", " "), len(list((d / "pages").glob("*.txt")))))
    tabs = TEXT / "tables"
    tcount = []
    for f in sorted(tabs.glob("*.csv")) if tabs.is_dir() else []:
        n = sum(1 for _ in open(f, encoding="utf-8")) - 1
        tcount.append("|-\n| <code>%s</code> || %d" % (f.name, n))
    write_page(con, "SL100:Source books", STAMP % "Source_Text/" +
               "The Star Wars d20 books are the second source of game information after the Legends articles. Their text is "
               "copyrighted, so it is kept in <code>Source_Text/</code> on your computer and read through the private book browser, "
               "which only works on your own machine: '''[/books Open the source-book browser]''' (search all books, page by page).\n\n"
               '<div class="sl-cards small">\n{{SL100 Card|link=SL100:Collation|title=Collation reports|image=Holocron-NEGWT.png|text=d20 items matched to Legends articles, lists and checks.}}\n</div>\n\n'
               "== Books extracted ==\n{| class=\"wikitable sortable\"\n! Book !! Pages\n" + "\n".join(rows) + "\n|}\n\n"
               "== Stat tables pulled from the books ==\nRaw d20 values with book and page, in <code>Source_Text/tables/</code>; "
               "<code>wiki_match.csv</code> links each item to its Legends article.\n{| class=\"wikitable\"\n! File !! Rows\n" + "\n".join(tcount) + "\n|}\n\n[[Category:SL100]]")
    con.commit()


if __name__ == "__main__":
    main()

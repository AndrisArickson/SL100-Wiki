This module is used to create leaderboards for [[Wookieepedia:Star Wars Character of the Year]] and other similar contests.

==Usage instructions==
<code><nowiki>{{#invoke:COTY|votecount|contest=|year=|limit=}}</nowiki></code>

===Required parameters===
*{{Para|year}} Year of the contest.

===Optional parameters===
*{{Para|contest}} Type of the contest, for example "Character" or "Creator". Defaults to "Character".
*{{Para|limit}} Maximum number of nominees to be listed. Defaults to 50.

